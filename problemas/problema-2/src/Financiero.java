       private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed

      double precioBase = Double.parseDouble(txtPrecio.getText());


    // Obtener los valores de las proposiciones lógicas.

        // Obtener los valores de las proposiciones lógicas.
        // p: el comprador es estudiante acreditado.
        // q: el equipo pertenece al catálogo educativo.
        boolean p = chkEstudiante.isSelected();
        boolean q = chkEducativo.isSelected();

        // Variables para almacenar la tasa y la política fiscal.
        double porcentajeImpuesto;
        String politicaFiscal;

        // Conjunción lógica AND: ambas proposiciones son verdaderas.
        // Se aplica una exención total del impuesto.
        if (p && q) {
            porcentajeImpuesto = 0.00;
            politicaFiscal = "Exención Total de Impuesto (Tasa 0%)";

        // Disyunción exclusiva XOR: solo una proposición es verdadera.
        // Se aplica un impuesto reducido del 8%.
        } else if (p ^ q) {
            porcentajeImpuesto = 0.08;
            politicaFiscal = "Impuesto Subvencionado / Reducido (Tasa 8%)";

        // Si ambas proposiciones son falsas, se aplica el 16%.
        } else {
            porcentajeImpuesto = 0.16;
            politicaFiscal = "Impuesto General Standard (Tasa 16%)";
        }

        // Calcular el importe del impuesto correspondiente.
        double montoImpuesto = precioBase * porcentajeImpuesto;

        // Obtener el precio final sumando el impuesto al precio base.
        double totalPagar = precioBase + montoImpuesto;

        // Mostrar el dictamen fiscal y financiero con dos decimales.
        txtResultado.setText(
            "--- DICTAMEN FISCAL Y FINANCIERO ---\n" +
            String.format("Precio Base del Equipo: $%.2f\n", precioBase) +
            "Proposición p (Estudiante): " + (p ? "1 (Verdadero)" : "0 (Falso)") + "\n" +
            "Proposición q (Educativo): " + (q ? "1 (Verdadero)" : "0 (Falso)") + "\n" +
            "Política Aplicada: " + politicaFiscal + "\n" +
            String.format("Monto de Impuesto: $%.2f\n", montoImpuesto) +
            String.format("TOTAL FINAL A PAGAR: $%.2f", totalPagar)
        );

    }//GEN-LAST:event_btnCalcularActionPerformed


