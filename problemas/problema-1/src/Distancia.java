    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // Se leen los valores escritos en los campos de texto y se convierten de String a float
        float x1 = Float.parseFloat(txtX1.getText());
        float y1 = Float.parseFloat(txtY1.getText());
        float x2 = Float.parseFloat(txtX2.getText());
        float y2 = Float.parseFloat(txtY2.getText());

        // Se calcula cuánto cambia cada coordenada entre el punto 1 y el punto 2 (incrementos)
        float incrementoX = x2 - x1; // ΔX = x2 - x1
    float incrementoY = y2 - y1; // ΔY = y2 - y1

        // Fórmula de la distancia: raíz cuadrada de (ΔX² + ΔY²)
        // Math.pow(base, 2) eleva al cuadrado y Math.sqrt() saca la raíz cuadrada
        double distancia = Math.sqrt(Math.pow(incrementoX, 2) + Math.pow(incrementoY, 2));

        // Se muestran los resultados en los labels, con 2 decimales (%.2f)
        lblIncX.setText(String.format("Incremento de X: %.2f", incrementoX));
        lblIncY.setText(String.format("Incremento de Y: %.2f", incrementoY));
        lblResultado.setText(String.format("La distancia es: %.2f", distancia));
    }//GEN-LAST:event_btnCalcularActionPerformed

